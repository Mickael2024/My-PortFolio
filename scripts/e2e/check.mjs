import puppeteer from 'puppeteer-core'
const S = process.argv[2]
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--disable-gpu'] })
const errors = []
const page = await browser.newPage()
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) errors.push(`[${m.type()}] ${m.text()}`) })
page.on('pageerror', (e) => errors.push(`[pageerror] ${e.message}`))
page.on('requestfailed', (r) => errors.push(`[requestfailed] ${r.url()}`))
page.on('response', (r) => { if (r.status() >= 400) errors.push(`[http ${r.status()}] ${r.url()}`) })

await page.setViewport({ width: 1440, height: 900 })
await page.goto('http://localhost:4173/', { waitUntil: 'networkidle0' })
// Débordement horizontal ?
const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
console.log('overflow desktop px:', overflow)
// Modale projet
await page.click('#projects article button')
await page.waitForSelector('[role=dialog]')
await new Promise((r) => setTimeout(r, 600))
await page.screenshot({ path: `${S}/modal.png` })
console.log('modal title:', await page.$eval('#project-title', (e) => e.textContent))
await page.keyboard.press('Escape')
await new Promise((r) => setTimeout(r, 400))
console.log('modal closed:', (await page.$('[role=dialog]')) === null)
// Filtre + recherche
await page.evaluate(() => document.getElementById('projects').scrollIntoView())
const tabs = await page.$$('#projects [role=tab]')
await tabs[2].click()
await new Promise((r) => setTimeout(r, 500))
console.log('cards embarque:', (await page.$$('#projects article')).length)
await page.type('#projects input[type=search]', 'kicad')
await new Promise((r) => setTimeout(r, 400))
console.log('cards search kicad:', (await page.$$('#projects article')).length)
// Lien data-project depuis Expertises
await page.evaluate(() => document.querySelector('#expertise a[data-project="smartcount"]').click())
await new Promise((r) => setTimeout(r, 700))
console.log('modal from expertise:', await page.$eval('#project-title', (e) => e.textContent))
await page.keyboard.press('Escape')
// Bascule EN
await page.click('header button[aria-label]')
await new Promise((r) => setTimeout(r, 400))
console.log('lang:', await page.evaluate(() => document.documentElement.lang), '| h1:', await page.$eval('h1', (e) => e.textContent))
await page.evaluate(() => window.scrollTo(0, 0))
await new Promise((r) => setTimeout(r, 800))
await page.screenshot({ path: `${S}/hero-en.png` })
// Formulaire : validation
await page.evaluate(() => document.getElementById('contact').scrollIntoView())
await page.click('#contact form button[type=submit]').catch(() => console.log('submit disabled (pas de backend) : ok'))
console.log('submit disabled:', await page.$eval('#contact form button[type=submit]', (b) => b.disabled))
// Mobile
await page.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true })
await page.goto('http://localhost:4173/', { waitUntil: 'networkidle0' })
const overflowM = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
console.log('overflow mobile px:', overflowM)
await page.click('button[aria-controls=mobile-menu]')
await new Promise((r) => setTimeout(r, 500))
await page.screenshot({ path: `${S}/mobile-menu.png` })
console.log('mobile menu open:', (await page.$('#mobile-menu')) !== null)
await page.click('#mobile-menu a[href="#projects"]')
await new Promise((r) => setTimeout(r, 900))
console.log('menu closed after nav:', (await page.$('#mobile-menu')) === null)
await page.screenshot({ path: `${S}/mobile-projects.png` })
await page.click('#projects article button')
await new Promise((r) => setTimeout(r, 700))
await page.screenshot({ path: `${S}/mobile-modal.png` })
console.log('\nERRORS:', errors.length ? errors.join('\n') : 'none')
await browser.close()
